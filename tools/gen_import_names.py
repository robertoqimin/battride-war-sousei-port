#!/usr/bin/env python3
"""Write port/src/import_names_kr.inc: NID -> symbol for every import of this game (eboot and
linked modules) that bbport's import_names*.inc do not name. Names come from shadPS4's aerolib
(public PS4 symbol lists). Run from ~/kr-port after link_modules.py."""
import json, re
aero = dict(re.findall(r'STUB\(\s*"([^"]{11})"\s*,\s*([A-Za-z0-9_]+)\s*\)',
                       open('refs/shadPS4/src/core/aerolib/aerolib.inl').read()))
known = set()
for f in ('port/src/import_names.inc', 'port/src/import_names_extra.inc'):
    known |= {m.split('#')[0] for m in re.findall(r'\{"([^"]+)"', open(f).read())}
link = json.load(open('out/link.json'))
nids = sorted({n.split('#')[0] for n in link['unresolved_imports']} - known)
lines = ['/* kr-port: generated by tools/gen_import_names.py; names from shadPS4 aerolib. */']
missing = 0
for nid in nids:
    if nid in aero: lines.append(f'{{"{nid}","{aero[nid]}"}},')
    else: missing += 1
open('port/src/import_names_kr.inc', 'w').write('\n'.join(lines) + '\n')
print(f'{len(lines) - 1} names added, {missing} NIDs without a public name')
